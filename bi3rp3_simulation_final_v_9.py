def visualise_grid(env, agent_pos):
    """
    Convert simulation grid values into display codes:
    0 = neutral (white)
    1 = trap (red)
    2 = source (green)
    3 = agent (blue)
    """
    frame = np.zeros_like(env, dtype=int)
    frame[env == 0] = 0
    frame[env == E_SINK] = 1
    frame[env == E_SOURCE] = 2
    x, y = agent_pos
    frame[x, y] = 3
    return frame

def run_trial_with_frames(agent):
    """
    Run one full trial and store grid frames for animation.
    """
    env = init_grid()
    pos = (GRID // 2, GRID // 2)
    energy = ENERGY_START
    frames = []
    energy_trace = []
    for t in range(N_STEPS):
        if energy <= 0:
            break
        frames.append(visualise_grid(env, pos))
        if agent == "random":
            a = random_move(env, pos, energy)
        elif agent == "greedy":
            a = greedy_move(env, pos, energy)
        elif agent == "cef":
            a = cef_move(env, pos, energy)
        else:
            raise ValueError("Unknown agent type")
        new_pos = move_pos(pos, a)
        cell = env[new_pos]
        energy = energy + cell - STEP_COST
        if cell == E_SOURCE:
            env[new_pos] = 0
        energy_trace.append(max(energy, 0))
        pos = new_pos
        if np.random.rand() < RELOCATION_P:
            env = init_grid()
    return {
        "frames": frames,
        "energy_trace": np.array(energy_trace)
    }

def generate_visual_trials(seed=MAIN_SEED):
    """
    Generate one representative animated trial for each agent.
    """
    set_seed(seed)
    visual_results = {}
    for agent in AGENTS:
        visual_results[agent] = run_trial_with_frames(agent)
    return visual_results

def animate_visual_trials(visual_results, interval_ms=300):
    """
    Display one animated trial for each agent side by side.
    """
    cmap_env = mcolors.ListedColormap([
        "white",   # 0 neutral
        "red",     # 1 trap
        "green",   # 2 source
        "blue"     # 3 agent
    ])
    fig, axes = plt.subplots(
        1, 6, figsize=(18, 6),
        gridspec_kw={"width_ratios": [1, 0.6, 1, 0.6, 1, 0.6]}
    )
    plt.tight_layout()
    plt.close(fig)
    imgs = []
    bars = []
    max_frames = min(len(visual_results[a]["frames"]) for a in AGENTS)
    for i, agent in enumerate(AGENTS):
        ax_grid = axes[2 * i]
        ax_bar = axes[2 * i + 1]
        first_frame = visual_results[agent]["frames"][0]
        first_energy = visual_results[agent]["energy_trace"][0] if len(visual_results[agent]["energy_trace"]) > 0 else 0
        img = ax_grid.imshow(first_frame, cmap=cmap_env, vmin=0, vmax=3)
        ax_grid.set_title(agent.upper())
        ax_grid.set_xticks([])
        ax_grid.set_yticks([])
        bar = ax_bar.bar([0], [first_energy], color="blue")
        ax_bar.set_ylim(0, ENERGY_START)
        ax_bar.set_xticks([])
        ax_bar.set_title(f"Energy: {first_energy:.1f}")
        imgs.append(img)
        bars.append(bar)
    def update(frame_idx):
        artists = []
        for i, agent in enumerate(AGENTS):
            imgs[i].set_data(visual_results[agent]["frames"][frame_idx])
            if frame_idx < len(visual_results[agent]["energy_trace"]):
                energy_val = visual_results[agent]["energy_trace"][frame_idx]
            else:
                energy_val = 0
            bars[i][0].set_height(energy_val)
            axes[2 * i + 1].set_title(f"Energy: {energy_val:.1f}")
            artists.append(imgs[i])
            artists.append(bars[i][0])
        return artists
    anim = FuncAnimation(fig, update, frames=max_frames, interval=interval_ms, blit=False)
    return HTML(anim.to_jshtml())

# CELL 24: RUN ANIMATION

