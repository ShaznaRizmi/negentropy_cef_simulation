# CELL 3: RANDOM SEED FUNCTION

def set_seed(seed):
    """
    Set NumPy and Python random seeds for reproducibility.
    """
    np.random.seed(seed)
    random.seed(seed)

# CELL 4: ENVIRONMENT + MOVEMENT

def init_grid():
    """
    Create a sparse 20x20 environment:
    - 8% energy sources
    - 4% traps
    - 88% neutral cells
    """
    grid = np.zeros((GRID, GRID), dtype=int)
    probs = np.random.rand(GRID, GRID)
    grid[probs < P_SOURCE] = E_SOURCE
    grid[(probs >= P_SOURCE) & (probs < P_SOURCE + P_SINK)] = E_SINK
    return grid

# CELL 5: FUTURE-OPTIONS PROXY (CEF CORE IDEA)

def future_entropy_proxy(start_pos):
    """
    Approximate future optionality by simulating many short random
    rollouts from a candidate next position and counting the fraction
    of unique end positions reached.
    """
    reached = []
    for _ in range(MC_SAMPLES):
        pos = start_pos
        for _ in range(HORIZON):
            a = np.random.randint(len(MOVES))
            pos = move_pos(pos, a)
        reached.append(pos)
    return len(set(reached)) / MC_SAMPLES

# CELL 6: AGENT BEHAVIOURS

def random_move(grid, pos, energy):
    """
    Random agent: chooses any action uniformly at random.
    """
    return np.random.randint(len(MOVES))

def greedy_move(grid, pos, energy):
    """
    Greedy agent: chooses the move with the highest immediate cell value.
    A tiny penalty on staying still encourages movement.
    """
    best = 0
    best_val = -1e9
    for i in range(len(MOVES)):
        nx, ny = move_pos(pos, i)
        val = grid[nx, ny]
        if i == 0:
            val -= 0.1
        if val > best_val:
            best_val = val
            best = i
    return best

# CELL 7: SINGLE TRIAL SIMULATION

def run_trial(agent):
    """
    Run one complete trial for one agent.
    Returns:
    - steps: survival time
    - energy_trace: energy over time
    - final_energy: energy at the end of the trial
    """
    env = init_grid()
    pos = (GRID // 2, GRID // 2)
    energy = ENERGY_START
    energy_trace = []
    for t in range(N_STEPS):
        if energy <= 0:
            break
        if agent == "random":
            a = random_move(env, pos, energy)
        elif agent == "greedy":
            a = greedy_move(env, pos, energy)
        elif agent == "cef":
            a = cef_move(env, pos, energy)
        else:
            raise ValueError("Unknown agent type")
        new_pos = move_pos(pos, a)
        cell = env[new_pos]
        energy = energy + cell - STEP_COST
        # Consume energy source once visited
        if cell == E_SOURCE:
            env[new_pos] = 0
        energy_trace.append(max(energy, 0))
        pos = new_pos
        # Occasionally re-randomise environment
        if np.random.rand() < RELOCATION_P:
            env = init_grid()
    return {
        "steps": len(energy_trace),
        "energy_trace": np.array(energy_trace),
        "final_energy": energy
    }

# CELL 8: RUN FULL EXPERIMENT FOR ONE SEED

def run_experiment(seed):
    """
    Run all trials for all agent types under one chosen random seed.
    """
    set_seed(seed)
    results = {a: [] for a in AGENTS}
    for a in AGENTS:
        print("Running:", a)
        for _ in tqdm(range(N_TRIALS)):
            results[a].append(run_trial(a))
    return results

# CELL 9: EXTRACT METRICS

def extract_steps(results):
    """
    Extract survival times for each agent.
    """
    return {a: [r["steps"] for r in results[a]] for a in AGENTS}

def extract_final_energy(results):
    """
    Extract final energies for each agent.
    """
    return {a: [r["final_energy"] for r in results[a]] for a in AGENTS}

# CELL 10: STATISTICS

def run_stats(results):
    """
    Run:
    - one-way ANOVA
    - Kruskal-Wallis
    - pairwise Welch t-tests
    - Bonferroni correction
    """
    steps = extract_steps(results)
    r = steps["random"]
    g = steps["greedy"]
    c = steps["cef"]
    # One-way ANOVA
    F, p_anova = f_oneway(r, g, c)
    # Non-parametric check
    H, p_kw = kruskal(r, g, c)
    # Pairwise Welch t-tests
    tests = [
        ttest_ind(r, g, equal_var=False),
        ttest_ind(r, c, equal_var=False),
        ttest_ind(g, c, equal_var=False)
    ]
    pvals = [t.pvalue for t in tests]
    corrected = multipletests(pvals, method="bonferroni")
    return F, p_anova, H, p_kw, tests, corrected

# CELL 11: NEGENTROPY CALCULATION

def compute_negentropy(results, bins=12):
    """
    At each time step, compute Shannon entropy across trial energy values
    and convert it to negentropy
    """
    neg = {}
    for agent in AGENTS:
        max_len = max(len(r["energy_trace"]) for r in results[agent])
        arr = np.full((len(results[agent]), max_len), np.nan)
        for i, r in enumerate(results[agent]):
            arr[i, :len(r["energy_trace"])] = r["energy_trace"]
        neg_series = []
        for t in range(arr.shape[1]):
            vals = arr[:, t]
            vals = vals[~np.isnan(vals)]
            if len(vals) == 0:
                neg_series.append(np.nan)
                continue
            hist, _ = np.histogram(vals, bins=bins, range=(0, ENERGY_START))
            if np.sum(hist) == 0:
                neg_series.append(np.nan)
                continue
            p = hist / np.sum(hist)
            p = p + 1e-12  # avoid log(0)
            S = entropy(p, base=np.e)
            S_max = np.log(len(p))
            neg_series.append(S_max - S)
        neg[agent] = np.array(neg_series)
    return neg

